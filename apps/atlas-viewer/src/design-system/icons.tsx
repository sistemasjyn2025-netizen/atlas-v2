import type { CSSProperties } from 'react';

// ── Shared Types ─────────────────────────────────────────────────────────────

export interface IconProps {
  /** Icon width and height in pixels. @default 16 */
  size?: number;
  /** SVG fill/stroke color. @default 'currentColor' */
  color?: string;
  /** Additional CSS class name. */
  className?: string;
  /** Additional inline styles. */
  style?: CSSProperties;
  /** Accessible label. When provided, sets role="img" and aria-label. */
  'aria-label'?: string;
}

// ── Helper ───────────────────────────────────────────────────────────────────

function svgProps(
  props: IconProps,
  defaults?: { viewBox?: string },
) {
  const {
    size = 16,
    color = 'currentColor',
    className,
    style,
    'aria-label': ariaLabel,
  } = props;

  return {
    xmlns: 'http://www.w3.org/2000/svg' as const,
    width: size,
    height: size,
    viewBox: defaults?.viewBox ?? '0 0 24 24',
    fill: 'none' as const,
    stroke: color,
    strokeWidth: 2,
    strokeLinecap: 'round' as const,
    strokeLinejoin: 'round' as const,
    className,
    style: { flexShrink: 0, ...style } as CSSProperties,
    role: ariaLabel ? ('img' as const) : undefined,
    'aria-label': ariaLabel,
    'aria-hidden': ariaLabel ? undefined : (true as const),
  };
}

